test('список клиентов: строка открывает студию, чипы не переносятся', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'mobile', 'ширина чипов проверяется на 390px')
  await signIn(page, TOKENS.trainer)
  await page.goto('/clients')
  await expect(page.getByRole('link', { name: 'План' })).toHaveCount(0)
  const all = page.getByRole('button', { name: 'Все', exact: true })
  const withoutPlan = page.getByRole('button', { name: 'Без плана', exact: true })
  const allBox = await all.boundingBox()
  const withoutBox = await withoutPlan.boundingBox()
  expect(allBox).not.toBeNull()
  expect(withoutBox).not.toBeNull()
  if (!allBox || !withoutBox) return
  expect(Math.abs(allBox.y - withoutBox.y)).toBeLessThan(2)
  await page.getByRole('button', { name: /Анна Иванова/ }).click()
  await expect(page).toHaveURL(/\/clients\/profile\?clientUserId=/)
  await expect(page.getByRole('heading', { name: 'Анна Иванова' })).toBeVisible()
})

